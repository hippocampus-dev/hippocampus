#!/usr/bin/env bash

set -Eeo pipefail
trap 'echo "exit $?: $BASH_COMMAND(line $LINENO)" >&2' ERR

# setup.sh symlinks the files/ outputs into every user in _USERS, so they must stay
# world-readable even when the caller runs under a restrictive umask.
umask 022

function usage() {
  cat <<EOS
Usage:
   sync-agent-files.sh

Convert Claude Code configurations for Codex, Gemini, and opencode CLI.

Project-level synchronization:
  Feature     Claude Code  Codex       Gemini       opencode
  Skills      Source       Converted   Converted    Native
  Commands    Source       Not synced  Converted    Converted
  Agents      Source       Partial [1] Converted    Converted
  Hooks       Source       Partial [3] Partial [3]  Not synced
  Path rules  Source       Partial [5] Partial [5]  Partial [5]

Global synchronization:
  Feature     Claude Code  Codex       Gemini       opencode
  Skills      Source       Converted   Converted    Converted
  Commands    Source       Partial [2] Converted    Converted
  Agents      Source       Partial [1] Converted    Converted
  Hooks       Source       Partial [3] Partial [3]  Manual [4]
  Path rules  Source       Not synced  Not synced   Not synced

Notes:
  [1] Codex has no per-agent tool allow-list; read-only agents use a read-only sandbox.
  [2] Codex custom prompts are deprecated and do not support project scope.
  [3] Supported hook events and tool matchers are translated; hook payloads remain tool-specific.
  [4] Hook plugins are hand-maintained and are not synchronized by this script.
  [5] An exact directory/** matcher becomes directory-scoped instructions. Other
      globs become conditional references to the source rule because AGENTS.md
      does not enforce path globs.

Project-level:
  - Skills:   .claude/skills/   -> .codex/skills/, .gemini/skills/ (opencode reads .claude/skills/ natively)
  - Commands: .claude/commands/ -> .gemini/commands/, .opencode/commands/
  - Agents:   .claude/agents/   -> .codex/agents/, .gemini/agents/, .opencode/agents/
  - Path rules: .claude/rules/  -> directory-scoped AGENTS.md approximations

Global (\$CLAUDE_CONFIG_DIR):
  - commands/  -> files/.codex/prompts/, files/.gemini/commands/, files/.config/opencode/commands/
  - agents/    -> files/.codex/agents/, files/.gemini/agents/, files/.config/opencode/agents/
  - skills/    -> ~/.codex/skills/, ~/.gemini/skills/, files/.config/opencode/skills/
  - hooks      -> files/.codex/hooks.json, files/.gemini/settings.json (rewrites ~ in command paths to /home/node for sandbox)
                  (opencode reuses the hook scripts via files/.config/opencode/plugins/, hand-maintained)
  - CLAUDE.md  -> files/.codex/AGENTS.md, files/.gemini/AGENTS.md, files/.config/opencode/AGENTS.md

Note: the Global files/ outputs above are symlinked into ~ by setup.sh, so they stay
under version control. The project-level AGENTS.md approximations are not, since they
cite repository-relative paths. Global skills are written straight to ~ because codex
owns ~/.codex/skills/.system/ and must not have it captured by the repository.
EOS
}

