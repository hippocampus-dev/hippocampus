convert_skill() {
  local src="$1" dst="$2" content fm name desc keywords body short
  content=$(cat "$src")
  [[ "$content" =~ ^--- ]] || { echo "[WARN] No frontmatter: $src"; return; }

  fm=$(echo "$content" | awk '/^---$/{if(++c==2)exit}c' | tail -n +2)
  name=$(echo "$fm" | awk -F': ' '/^name:/{print $2}')
  desc=$(echo "$fm" | awk -F': ' '/^description:/{$1=""; sub(/^ /, ""); print}')
  keywords=$(echo "$fm" | awk -F': ' '/^keywords:/{$1=""; sub(/^ /, ""); print}')
  body=$(echo "$content" | awk '/^---$/{if(++c==2){p=1;next}}p')

  [ "${#desc}" -gt 500 ] && desc="${desc:0:497}..."

  mkdir -p "$(dirname "$dst")"

  if [ -n "$keywords" ]; then
    short=$(echo "$keywords" | xargs -r)
    cat > "$dst" <<EOF
---
# Generated by sync-agent-files.sh. DO NOT EDIT.
name: $name
description: $desc
metadata:
  short-description: $short
---
$body
EOF
  else
    cat > "$dst" <<EOF
---
# Generated by sync-agent-files.sh. DO NOT EDIT.
name: $name
description: $desc
---
$body
EOF
  fi
  echo "$src -> $dst"
}

convert_command() {
  local src="$1" dst="$2" content fm desc body
  content=$(cat "$src")
  [[ "$content" =~ ^--- ]] || { echo "[WARN] No frontmatter: $src"; return; }

  fm=$(echo "$content" | awk '/^---$/{if(++c==2)exit}c' | tail -n +2)
  desc=$(echo "$fm" | awk -F': ' '/^description:/{$1=""; sub(/^ /, ""); print}')
  body=$(echo "$content" \
    | awk '/^---$/{if(++c==2){p=1;next}}p' \
    | sed 's/\$ARGUMENTS/{{args}}/g' \
    | sed 's/^!`\(.*\)`$/!{\1}/')

  mkdir -p "$(dirname "$dst")"
  {
    echo "# Generated by sync-agent-files.sh. DO NOT EDIT."
    printf 'description = %s\n' "$(printf '%s' "$desc" | jq -Rs .)"
    printf 'prompt = %s\n' "$(printf '%s\n' "$body" | jq -Rs .)"
  } > "$dst"
  echo "$src -> $dst"
}

